CDN = "https://ucarecdn.stepik.net/"


def img(uid, w=None):
    width = f' width="{w}"' if w else ""
    return f'<p><img src="{CDN}{uid}/"{width} style="max-width:100%"></p>'


def q(n, lang):
    return f"<p><strong>{'Сұрақ' if lang == 'kz' else 'Вопрос'} №{n}.</strong></p>"


def html_table(rows, header=True):
    out = ['<table border="1" cellpadding="6" style="border-collapse:collapse">']
    for i, row in enumerate(rows):
        tag = "th" if header and i == 0 else "td"
        out.append("<tr>" + "".join(f"<{tag}>{c}</{tag}>" for c in row) + "</tr>")
    out.append("</table>")
    return "".join(out)


# ---------- конструкторлар ----------

def TEXT(kz, ru):
    return {"type": "text", "points": 0, "content": {"text": kz, "ru": {"text": ru}}}


def CHOICE(kz, ru, kz_opts, ru_opts, correct=0, points=1, multiple=False):
    cor = set(correct) if isinstance(correct, (list, tuple, set)) else {correct}
    mk = lambda opts: [{"text": t, "correct": i in cor} for i, t in enumerate(opts)]
    return {"type": "choice", "points": points,
            "content": {"text": kz, "options": mk(kz_opts), "multiple": multiple, "shuffle": True,
                        "max_attempts": 0, "partial": True, "explanation": "",
                        "ru": {"text": ru, "options": mk(ru_opts)}}}


def TABLE(kz, ru, kz_cols, ru_cols, kz_rows, ru_rows, points=2):
    mk = lambda rows: [{"text": t, "correct": c} for t, c in rows]
    return {"type": "table", "points": points,
            "content": {"text": kz, "columns": kz_cols, "rows": mk(kz_rows), "max_attempts": 0,
                        "partial": True, "explanation": "",
                        "ru": {"text": ru, "columns": ru_cols, "rows": mk(ru_rows)}}}


def NUMBER(kz, ru, answer, tol=0, points=1):
    return {"type": "number", "points": points,
            "content": {"text": kz, "answer": answer, "tolerance": tol, "max_attempts": 0, "partial": True,
                        "explanation": "", "ru": {"text": ru}}}


def BLANKS(kz, ru, points=1):
    return {"type": "fill_blanks", "points": points,
            "content": {"text": kz, "case_sensitive": False, "max_attempts": 0, "partial": True,
                        "explanation": "", "ru": {"text": ru}}}


